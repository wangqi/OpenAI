                    if let value = try? container.decode(Components.Schemas.RefusalContent.self) {
                        self = .refusal(value)
                        return
                    }
                    
                    throw DecodingError.dataCorruptedError(
                        in: container,
                        debugDescription: "ContentPart could not be decoded into any known type"
